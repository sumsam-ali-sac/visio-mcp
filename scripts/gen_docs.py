"""Regenerate the reference docs and the gallery from the code, so they never drift.

    uv run python scripts/gen_docs.py            # reference pages
    uv run python scripts/gen_docs.py --gallery  # also render examples/ to docs/gallery/*.png

Writes docs/reference/: diagram-spec.schema.json, patch-ops.schema.json, kinds.md, themes.md,
diagram-types.md, and one page per diagram type's ground rules.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from pydantic import TypeAdapter

from visio_mcp import catalog, rules, style
from visio_mcp.spec import DiagramSpec, PatchOp

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "docs" / "reference"
HEADER = "<!-- Generated by scripts/gen_docs.py — do not edit by hand. -->\n\n"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)}")


def schemas() -> None:
    write(REF / "diagram-spec.schema.json", json.dumps(DiagramSpec.model_json_schema(), indent=2) + "\n")
    write(REF / "patch-ops.schema.json", json.dumps(TypeAdapter(list[PatchOp]).json_schema(), indent=2) + "\n")


def kinds() -> None:
    lines = [HEADER, "# Shape kinds\n\n",
             "Use these in `nodes[].kind`. Aliases (e.g. `postgres` → `database`) also work; unknown kinds "
             "draw as a rectangle with a *did you mean* warning.\n\n"]
    by_cat = catalog.kinds_by_category()
    lines.append("## Generic kinds\n\n| Kind | Category | Shape | What it is for |\n|---|---|---|---|\n")
    for cat, ks in by_cat.items():
        for k in ks:
            if not k.provider:
                lines.append(f"| `{k.name}` | {cat} | {k.geometry} | {k.description} |\n")
    for provider, title in (("azure", "Azure"), ("aws", "AWS"), ("gcp", "Google Cloud")):
        lines.append(f"\n## {title}\n\nDraw with the official {title} icon once installed "
                     f"(`visio-ai icons install {provider}`); otherwise as a `base` shape in the provider's color.\n\n"
                     "| Kind | Category | Falls back to | Service |\n|---|---|---|---|\n")
        for k in sorted((k for k in catalog.kinds().values() if k.provider == provider), key=lambda k: k.name):
            lines.append(f"| `{k.name}` | {k.category} | `{k.base}` | {k.description} |\n")
    aliases = getattr(catalog, "_ALIASES", {})
    if aliases:
        lines.append("\n## Aliases\n\n| Alias | Kind |\n|---|---|\n")
        lines += [f"| `{a}` | `{k}` |\n" for a, k in sorted(aliases.items())]
    write(REF / "kinds.md", "".join(lines))


def themes() -> None:
    lines = [HEADER, "# Themes\n\nSet `\"theme\"` in the spec (or `--theme` / `/theme` in the CLI). "
             "`auto` picks `azure`/`aws`/`gcp` for cloud diagrams by provider, `c4` for C4 diagrams, "
             "otherwise `professional`.\n\n"]
    for t in style.THEMES.values():
        lines.append(f"## `{t.name}`\n\n{t.description}\n\n")
        lines.append(f"- Fonts: title **{t.title.font} {t.title.size:g} pt**, nodes "
                     f"{t.node_style('compute').text.font} {t.node_style('compute').text.size:g} pt bold, "
                     f"secondary {t.secondary.size:g} pt\n")
        lines.append(f"- Page background `{t.background}` · accent `{t.accent}` · edges `{t.edge.color}` "
                     f"{t.edge.weight:g} pt\n\n")
        lines.append("| Category | Fill | Line | Text |\n|---|---|---|---|\n")
        for cat in style.CATEGORIES:
            s = t.node_style(cat)
            lines.append(f"| {cat} | `{s.fill}` | `{s.line}` | `{s.text.color}` |\n")
        lines.append("\n| Group kind | Fill | Line | Pattern |\n|---|---|---|---|\n")
        for kind in ("generic", "tier", "system", "boundary", "cloud", "region", "zone", "network", "subnet",
                     "cluster", "environment", "lane", "external"):
            g = t.group_style(kind)
            lines.append(f"| {kind} | `{g.shape.fill}` | `{g.shape.line}` | {g.shape.line_pattern} |\n")
        lines.append("\n")
    write(REF / "themes.md", "".join(lines))


def diagram_types() -> None:
    summary = rules.type_summary()
    lines = [HEADER, "# Diagram types and ground rules\n\n",
             "Every type has conventions the AI follows and the linter checks. The full rules for a type are "
             "also served by the MCP tool `get_diagram_rules(type)` and by `visio-ai rules TYPE`.\n\n",
             "| Type | Use when | Rules |\n|---|---|---|\n"]
    for t in rules.TYPES:
        lines.append(f"| `{t}` | {summary.get(t, '')} | [rules](rules/{t}.md) |\n")
    lines.append("\nGeneral rules for every diagram: [rules/general.md](rules/general.md). Cloud providers: "
                 "[Azure](rules/cloud-azure.md), [AWS](rules/cloud-aws.md), [Google Cloud](rules/cloud-gcp.md).\n")
    write(REF / "diagram-types.md", "".join(lines))
    write(REF / "rules" / "general.md", HEADER + rules.general())
    for t in rules.TYPES:
        write(REF / "rules" / f"{t}.md", HEADER + rules.type_rules(t))
    for p in ("azure", "aws", "gcp"):
        write(REF / "rules" / f"cloud-{p}.md", HEADER + rules.provider_rules(p))


def gallery() -> None:
    from visio_mcp.engine import Drawer

    out = ROOT / "docs" / "gallery"
    out.mkdir(parents=True, exist_ok=True)
    drawer = Drawer(target="native")
    tmp = ROOT / "diagrams" / "gallery"
    for f in sorted((ROOT / "examples").glob("*.json")):
        spec = DiagramSpec.model_validate_json(f.read_text(encoding="utf-8"))
        res = drawer.render(spec, tmp / f"{f.stem}.vsdx", ["png"])
        if res.png:
            (out / f"{f.stem}.png").write_bytes(res.png.read_bytes())
            print(f"wrote docs/gallery/{f.stem}.png")
        else:
            print(f"skipped {f.stem}: no PNG renderer (install the preview extra or LibreOffice)")


if __name__ == "__main__":
    schemas()
    kinds()
    themes()
    diagram_types()
    if "--gallery" in sys.argv:
        gallery()
